"""
Monthly update check for RetailMarket PH.

1) Compares each utility's captive rate in data.js with the newest URR filing summary.
2) Optionally compares the current data.js with last month's copy (--previous).
Writes changes.js (shown in the app under ⚡ > What changed) and CHANGES_REPORT.md.
Nothing in data.js is overwritten: review the report, then update the source data.

Usage (from the app folder):
    python3 tools/update_check.py "<URR master summary .md>" [--previous old/data.js]
Default summary: ../../7. URR Data/urr_ongrid_markdown_2026/00_NATIONAL_ONGRID_URR_MASTER_SUMMARY_SEPTEMBER_2026.md
"""
import json, os, re, sys, datetime

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT = os.path.join(APP, "..", "..", "7. URR Data", "urr_ongrid_markdown_2026",
                       "00_NATIONAL_ONGRID_URR_MASTER_SUMMARY_SEPTEMBER_2026.md")
BIG_CHANGE = 0.25  # flag rate moves above 25% for checking

def load_js(path):
    s = open(path).read()
    return json.loads(s[s.index("=") + 1:].rstrip().rstrip(";"))

def norm(n):
    n = n.lower().replace("&", "and")
    n = re.sub(r"\b(inc|incorporated|co|corp|corporation|company|the)\b\.?", " ", n)
    return re.sub(r"[^a-z0-9]+", "", n)

def parse_summary(path):
    txt = open(path, encoding="utf-8").read()
    m = re.search(r"(JANUARY|FEBRUARY|MARCH|APRIL|MAY|JUNE|JULY|AUGUST|SEPTEMBER|OCTOBER|NOVEMBER|DECEMBER)_(\d{4})", os.path.basename(path), re.I)
    month = f"{m.group(1).title()[:3]} {m.group(2)}" if m else "latest"
    rows = []
    for line in txt.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 5 and cells[0].isdigit():
            name = cells[1].strip("* ")
            rate = re.search(r"([\d.]+)", cells[4].replace(",", ""))
            if rate:
                rows.append({"name": name, "rate": float(rate.group(1)), "kwh": cells[2]})
    return month, rows

def main():
    args = sys.argv[1:]
    prev = None
    if "--previous" in args:
        i = args.index("--previous"); prev = args[i + 1]; del args[i:i + 2]
    src = args[0] if args else DEFAULT
    data = load_js(os.path.join(APP, "data.js"))
    month, rows = parse_summary(src)
    by_name = {norm(r["name"]): r for r in rows}

    rate_changes, unmatched = [], []
    for du in data["dus"]:
        r = by_name.get(norm(du["name"]))
        if not r:
            unmatched.append(du["acronym"]); continue
        old = float(re.search(r"[\d.]+", du["base_rate"]).group())
        if r["rate"] <= 0 or old <= 0:
            unmatched.append(f"{du['acronym']} (no usable rate)"); continue
        delta = r["rate"] - old
        rate_changes.append({
            "acronym": du["acronym"], "id": du["id"], "old_rate": old, "old_month": du.get("urr_month"),
            "new_rate": r["rate"], "new_month": month, "delta": round(delta, 4),
            "pct": round(delta / old * 100, 1) if old else None,
            "check": bool(old and abs(delta / old) > BIG_CHANGE),
        })
    rate_changes.sort(key=lambda x: -abs(x["pct"] or 0))

    data_changes = []
    if prev:
        p = load_js(prev)
        def tot(d, k): return sum((x.get(k) or 0) for x in d["dus"])
        for k, label in [("crem_eus", "CREM end-users"), ("crem_mw", "CREM MW"), ("geop_eus", "GEOP end-users"),
                         ("geop_mw", "GEOP MW"), ("rap_groups", "RAP groups"), ("rap_mw", "RAP MW")]:
            a, b = tot(p, k), tot(data, k)
            if round(a, 2) != round(b, 2):
                data_changes.append({"metric": label, "before": round(a, 2), "after": round(b, 2)})
        pa = {x["acronym"] for x in p["dus"]}; ca = {x["acronym"] for x in data["dus"]}
        for a in sorted(ca - pa): data_changes.append({"metric": "Utility added", "after": a})
        for a in sorted(pa - ca): data_changes.append({"metric": "Utility removed", "before": a})

    out = {"generated": datetime.date.today().isoformat(), "urr_source": os.path.basename(src),
           "urr_month": month, "rate_changes": rate_changes, "unmatched": unmatched, "data_changes": data_changes}
    with open(os.path.join(APP, "changes.js"), "w") as f:
        f.write("// Generated by tools/update_check.py\nwindow.RETAIL_MARKET_CHANGES = ")
        json.dump(out, f, indent=1); f.write(";\n")

    L = [f"# What changed — {out['generated']}", "",
         f"Captive rates in data.js compared with **{os.path.basename(src)}** ({month}).",
         f"{len(rate_changes)} utilities matched; {len(unmatched)} not found in the URR summary.", "",
         "| Utility | In app | Latest URR | Change | Check? |", "|---|---|---|---|---|"]
    for c in rate_changes:
        L.append(f"| {c['acronym']} | ₱{c['old_rate']:.4f} ({c['old_month']}) | ₱{c['new_rate']:.4f} ({month}) | "
                 f"{c['delta']:+.4f} ({'n/a' if c['pct'] is None else format(c['pct'], '+.1f') + '%'}) | {'⚑ over 25%' if c['check'] else ''} |")
    if unmatched:
        L += ["", "Not in the URR summary: " + ", ".join(unmatched)]
    if data_changes:
        L += ["", "## Changes vs previous data.js", ""] + [f"- {d['metric']}: {d.get('before','')} → {d.get('after','')}" for d in data_changes]
    open(os.path.join(APP, "CHANGES_REPORT.md"), "w").write("\n".join(L) + "\n")
    print(f"changes.js and CHANGES_REPORT.md written: {len(rate_changes)} matched, "
          f"{sum(c['check'] for c in rate_changes)} moves over 25%, {len(unmatched)} unmatched")

if __name__ == "__main__":
    main()
